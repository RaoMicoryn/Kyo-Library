export function uid() {
  return "b" + Date.now().toString(36) + Math.random().toString(36).slice(2, 7);
}

function hash(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0;
  return Math.abs(h);
}

export function gradientFor(book) {
  return GRADS[hash(book.title + book.author) % GRADS.length];
}

export function metaLine(b) {
  const parts = [];
  if (b.genre) parts.push(b.genre);
  if (b.year !== "" && b.year != null) parts.push(b.year);
  return parts.join(" • ");
}

// Downscale an uploaded image so it fits comfortably in localStorage.
export function resizeImage(file, max = 640) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onerror = reject;
    reader.onload = () => {
      const img = new Image();
      img.onerror = reject;
      img.onload = () => {
        const s = Math.min(1, max / img.width);
        const c = document.createElement("canvas");
        c.width = Math.round(img.width * s);
        c.height = Math.round(img.height * s);
        c.getContext("2d").drawImage(img, 0, 0, c.width, c.height);
        resolve(c.toDataURL("image/jpeg", 0.82));
      };
      img.src = reader.result;
    };
    reader.readAsDataURL(file);
  });
}
